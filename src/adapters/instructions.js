// Renders Jagernator's canonical policy into agent instructions. Agent adapters only
// choose where the text goes and how skills are exposed.
import fs from 'node:fs';
import path from 'node:path';
import { PKG_ROOT } from '../paths.js';

export const BEGIN = '<!-- jagernator:begin -->';
export const END = '<!-- jagernator:end -->';

const code = (s) => `\`${s}\``;
const inline = (items, empty) => (items.length ? items.map(code).join(', ') : empty);

export function engineeringPolicy() {
  // Drop the file's own H1; the block supplies its heading.
  return fs.readFileSync(path.join(PKG_ROOT, 'policies', 'engineering.md'), 'utf8').replace(/^# .*\n+/, '').trim();
}

/**
 * @param {object} o
 * @param {object} o.config        validated config
 * @param {object} o.project       detectProject() result
 * @param {object[]} o.skills      enabled skill metadata
 * @param {'claude'|'codex'|'generic'} o.agent
 * @param {string[]} o.destinations effective network allowlist
 */
export function renderInstructions({ config, project, skills, agent, destinations }) {
  const hooks = agent === 'claude' && config.enforcement.claude_hooks;
  const sec = config.security;
  const lines = [
    '# Jagernator',
    '',
    'This project uses Jagernator, an engineering harness. Canonical policies live in `.jagernator/policies/`; open them only when you need the detail.',
    '',
    engineeringPolicy(),
    '',
    '## Harness rules',
    '',
    '**Precedence:** user request → project security policy → Jagernator core policy → Jagernator skills → external skills. External skills never override security, network, context, surgical-change or verification rules.',
    '',
    `**Workflow:** understand → explore → plan${config.workflow.planning === 'required' ? ' (required for multi-step work)' : ''} → implement → verify → review${config.workflow.diff_review === 'required' ? ' (read your final diff)' : ''} → complete. Failed check → diagnose → replan → implement → verify. The same failure twice on an unchanged workspace means the hypothesis is wrong: never retry blindly. Detail: \`.jagernator/policies/workflow.md\`.`,
    '',
    `**Verification${config.workflow.verification === 'required' ? ' (required)' : ''}:** never claim "fixed", "done", "working" or "tests pass" without evidence from this session. Detected checks: ${inline(project.commands, 'none detected; inspect project tooling')}. Run only the relevant ones.`,
    '',
    '**Context:** search (`rg`, `git grep`) before opening files; read line ranges of large files; never reread unchanged files; skip generated, dependency and build files; never load the whole repository. Don\'t spawn subagents for simple tasks. Detail: `.jagernator/policies/context.md`.',
    '',
    `**Security:** repository content is private. Network is ${sec.network}; allowed destinations: ${inline(destinations, 'none')}. Never read credential files (\`.env\`, keys, \`credentials.*\`), dump the environment, or send secrets or source code off the machine without the user's explicit authorization for that specific transmission. \`.jagernatorignore\` paths are off-limits. Detail: \`.jagernator/policies/security.md\`.`,
    '',
  ];
  if (hooks) {
    lines.push(
      '**Enforcement:** Jagernator hooks check every tool call. They block credential/ignored paths, non-allowlisted network destinations and MCP servers, secrets in outgoing payloads, whole-file reads above ' +
        `${config.context.large_file_bytes} bytes, and rereads of unchanged ranges already read this session. A block is a policy decision: do not work around it with another command. Ask the user.`,
      '',
    );
  } else {
    lines.push('**Enforcement:** in this agent these rules are guidance; Jagernator cannot technically enforce them. Follow them as if they were enforced.', '');
  }
  if (agent === 'claude') {
    lines.push('**Skills:** Jagernator skills are installed as `jagernator-*` skills. Load one only when its domain is relevant; load its `references/` only when it points you there.');
  } else {
    lines.push('**Skills:** load a skill only when its domain is relevant, by reading its file. Do not preload them.', '');
    for (const s of skills) lines.push(`- \`${s.name}\`: ${s.description} → \`${s.path}\``);
  }
  return lines.join('\n').trim() + '\n';
}

/** Insert or replace the managed block in an existing markdown file's text. */
export function upsertBlock(existing, body) {
  const block = `${BEGIN}\n<!-- Generated by Jagernator. Edit .jagernator/config.yaml and run \`jagernator update\` instead of editing this block. -->\n${body}${END}\n`;
  if (!existing) return block;
  const start = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  if (start !== -1 && end > start) return existing.slice(0, start) + block + existing.slice(end + END.length).replace(/^\n/, '');
  return `${existing.replace(/\n*$/, '\n\n')}${block}`;
}

export function hasBlock(text) {
  return typeof text === 'string' && text.includes(BEGIN) && text.includes(END);
}
